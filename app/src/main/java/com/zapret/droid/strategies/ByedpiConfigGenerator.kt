package com.zapret.droid.strategies

data class ByedpiCandidate(
    val id: String,
    val arguments: String,
    val description: String
)

object ByedpiConfigGenerator {
    private val splitPositions = listOf("1", "2", "3", "6", "9", "12", "15", "20", "25", "30", "35", "99")
    private val splitModes = listOf("+s", "+se", "+sm", "+h", "+n", "-4+s")
    private val disorderPositions = listOf("1", "3", "4", "6", "9", "12", "15", "20", "21", "25", "30", "35", "89", "94:3:2")
    private val disorderModes = listOf("+s", "+se", "+sm", "+h", "+n", "")
    private val fakeCounts = listOf("1", "2", "3", "4", "6", "8")
    private val cutoffs = listOf("1", "2", "3", "4", "7", "11")

    fun generate(seed: Long, serial: Int, count: Int): List<ByedpiCandidate> {
        if (count <= 0) return emptyList()

        return (0 until count).map { offset ->
            val candidateIndex = serial + offset
            val random = RandomState(seed, candidateIndex)
            val arguments = mutableListOf<String>()

            if (random.nextBoolean()) arguments.add("-o${random.pick(fakeCounts)}")
            repeat(random.nextInt(2, 5)) {
                val position = random.pick(splitPositions)
                val mode = random.pick(splitModes)
                arguments.add("-s$position$mode")
            }
            repeat(random.nextInt(1, 4)) {
                val position = random.pick(disorderPositions)
                val mode = random.pick(disorderModes)
                arguments.add("-d$position$mode")
            }
            if (random.nextBoolean()) arguments.add("-r${random.pick(fakeCounts)}")
            if (random.nextBoolean()) arguments.add("-f${random.pick(cutoffs)}")
            if (random.nextBoolean()) arguments.add("-S")
            if (random.nextBoolean()) arguments.add("-K")
            if (random.nextBoolean()) arguments.add("-T0.001")
            if (random.nextBoolean()) arguments.add("-An")

            val line = arguments.joinToString(" ")
            ByedpiCandidate(
                id = "byedpi-${seed}-${candidateIndex}",
                arguments = line,
                description = "Новый кандидат seed=$seed, номер=$candidateIndex"
            )
        }
    }

    fun export(candidates: List<ByedpiCandidate>, seed: Long): String =
        buildString {
            appendLine("# Generated ByeDPI config")
            appendLine("# seed=$seed")
            appendLine()
            candidates.forEachIndexed { index, candidate ->
                appendLine("# ${index + 1}: ${candidate.description}")
                appendLine(candidate.arguments)
                appendLine()
            }
        }.trimEnd()

    private class RandomState(seed: Long, index: Int) {
        private var state = ((seed xor (index.toLong() * 0x9e3779b9L)) * 0x41c64e6bL)
            .and(0x7fffffffffffffffL)

        fun nextBoolean(): Boolean = nextInt(0, 2) == 1

        fun nextInt(from: Int, toExclusive: Int): Int {
            if (toExclusive <= from) return from
            val span = toExclusive - from
            val value = (nextLong() % span).toInt()
            return from + if (value < 0) value + span else value
        }

        fun <T> pick(values: List<T>): T = values[nextInt(0, values.size)]

        private fun nextLong(): Long {
            state = (state * 6364136223846793005L + 1442695040888963407L).and(0x7fffffffffffffffL)
            return state
        }
    }
}
